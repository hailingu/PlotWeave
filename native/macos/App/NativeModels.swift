import Foundation
import Synchronization

/// Provider POST inputs remain inside Swift and never project plaintext credentials back to the Web.
struct NativeProviderRequest: Sendable {
    /// Endpoint, body and limits describe one whole generation/chat POST including redirected response reads.
    let url: URL
    /// Decrypted key exists only for this in-flight request and is never returned to the page.
    let key: String
    /// Existing OpenAI-compatible body carries model/messages or prompt/size without new fields.
    let body: HostJSON
    /// The monotonic stage deadline includes redirects and body reads.
    let deadline: ContinuousClock.Instant
    /// Decoded response bytes are capped before JSON materialization.
    let maximum: Int
}

/// Native model lifecycle owns every cancellation flag and submits generated bytes to the project actor.
actor NativeModels {
    /// Injected protocol-compatible POST avoids real billing and network in tests.
    typealias Post = @Sendable (NativeProviderRequest) async throws -> NativeHTTPReply
    /// URL image fallback is independently policy-bound and test-injectable.
    typealias Download = @Sendable (String, ContinuousClock.Instant, @Sendable () -> Bool) async throws -> Data
    /// Preferences and project storage are shared with the host's ordinary IPC owners.
    let preferences: NativePreferences
    /// Generated assets share the same actor/deletion barrier as ordinary project commands.
    let projects: NativeProjectStore
    /// One provider POST seam is injected for isolated HTTP tests.
    let post: Post
    /// URL fallback enters the separately validated readonly HTTPS downloader.
    let download: Download

    /// Active image flags remain independently readable inside the queued project commit.
    private var active: [String: NativeModelCancellation] = [:]
    /// Unknown/late cancellations are deduplicated and bounded, matching the existing 64-entry FIFO.
    private var tombstones: [String] = []
    /// A closed service cannot begin more billable operations or reopen its injected data owners.
    private var closed = false

    /// Production services share their actors; no credential/keychain root is synthesized here.
    init(preferences: NativePreferences, projects: NativeProjectStore) {
        self.preferences = preferences
        self.projects = projects
        let provider = NativeProviderHTTP()
        let downloader = NativePublicDownload()
        post = provider.post
        download = { value, deadline, cancelled in try await downloader.fetch(value, deadline: deadline, isCancelled: cancelled) }
    }

    /// Test seams retain the real credential and storage owners while replacing only external HTTP.
    init(preferences: NativePreferences, projects: NativeProjectStore, post: @escaping Post, download: @escaping Download) {
        self.preferences = preferences
        self.projects = projects
        self.post = post
        self.download = download
    }

    /// Existing chat/image/cancel IPC returns business values and never a nested reply envelope.
    func invoke(command: String, args: [String: HostJSON]) async throws -> HostJSON {
        guard !closed else { throw HostFailure(code: "PW_CORE_CLOSED", message: "原生模型服务已关闭") }
        switch command {
        case "llm_chat": return try await chat(args)
        case "llm_image_generate":
            guard let request = args["request"]?.object else { throw invalid("缺少生图 request") }
            return try await image(request)
        case "llm_image_cancel": return .object(["cancelled": .bool(cancel(try string(args, "jobId")))])
        default: throw HostFailure(code: "PW_HOST_COMMAND_UNAVAILABLE", message: "未支持的模型命令")
        }
    }

    /// Host teardown cooperatively invalidates every queued or active image commit.
    func close() {
        closed = true
        for flag in active.values { flag.cancel() }
        active.removeAll()
        tombstones.removeAll()
    }

    /// Credential lookup stays in the prefs actor; the existing chat request/assistant JSON shape is retained.
    private func chat(_ args: [String: HostJSON]) async throws -> HostJSON {
        let provider = try string(args, "providerId")
        try NativeSeal.validateProvider(provider)
        let model = try selectedModel(args)
        let url = try endpoint(string(args, "baseUrl"), suffix: "chat/completions")
        guard let messages = args["messages"] else { throw invalid("缺少 messages") }
        let key = try await preferences.providerSecret(provider)
        guard !closed else { throw HostFailure(code: "PW_CORE_CLOSED", message: "原生模型服务已关闭") }
        try Task.checkCancellation()
        var body: [String: HostJSON] = ["model": .string(model), "messages": messages, "stream": .bool(false)]
        if let tools = args["tools"]?.arrayValue, !tools.isEmpty { body["tools"] = .array(tools); body["tool_choice"] = .string("auto") }
        let request = NativeProviderRequest(url: url, key: key, body: .object(body), deadline: .now.advanced(by: .seconds(120)), maximum: 16 * 1024 * 1024)
        let response = try await NativeDeadline.run(until: request.deadline) { try await self.post(request) }
        let parsed = try parse(response, key: key, url: url, maximum: request.maximum)
        guard let message = parsed["choices"]?.arrayValue?.first?["message"], message.object != nil else { throw invalid("服务未返回回复内容") }
        return message
    }

    /// One job owns its monotonic total budget, registration and flag through the final durable media commit.
    private func image(_ args: [String: HostJSON]) async throws -> HostJSON {
        let deadline = ContinuousClock.now.advanced(by: .seconds(600))
        let job = try string(args, "jobId")
        guard !job.isEmpty, active[job] == nil else { throw invalid("生图 jobId 为空或已在运行") }
        let flag = NativeModelCancellation()
        if let index = tombstones.firstIndex(of: job) { tombstones.remove(at: index); flag.cancel() }
        active[job] = flag
        defer { flag.cancel(); active.removeValue(forKey: job) }
        return try await withTaskCancellationHandler {
            try flag.check(deadline)
            let project = try string(args, "projectId")
            try NativeProjectEnvelope.validateID(project)
            let provider = try string(args, "providerId")
            try NativeSeal.validateProvider(provider)
            let model = try selectedModel(args)
            let prompt = try string(args, "prompt").trimmingCharacters(in: .whitespacesAndNewlines)
            guard !prompt.isEmpty else { throw invalid("Prompt 不能为空") }
            let size = try string(args, "size")
            let url = try endpoint(string(args, "baseUrl"), suffix: "images/generations")
            let key = try await NativeDeadline.run(until: deadline) { try await self.preferences.providerSecret(provider) }
            try flag.check(deadline)
            /// Existing OpenAI-compatible body carries model/messages or prompt/size without new fields.
    let body: HostJSON = .object(["model": .string(model), "prompt": .string(prompt), "size": .string(size)])
            let bytes = try await imageBytes(url: url, key: key, body: body, flag: flag, deadline: deadline)
            guard bytes.count <= 32 * 1024 * 1024, let mime = Self.imageMIME(bytes) else { throw invalid("生成内容超过上限或不是支持的图像格式（PNG/JPEG/WebP/GIF）") }
            try flag.check(deadline)
            let suffix = NativeAssetContract.fileExtension(name: "", mime: mime, generated: true)
            return try await NativeDeadline.run(until: deadline) {
                try await self.projects.importMedia(id: project, bytes: bytes, mime: mime, source: "generated", extension: suffix,
                    isCancelled: { flag.isCancelled || deadline <= .now })
            }
        } onCancel: { flag.cancel() }
    }

    /// Base64 is preferred; invalid/missing base64 enters the separately pinned HTTPS downloader.
    private func imageBytes(url: URL, key: String, body: HostJSON, flag: NativeModelCancellation, deadline: ContinuousClock.Instant) async throws -> Data {
        let request = NativeProviderRequest(url: url, key: key, body: body, deadline: min(deadline, .now.advanced(by: .seconds(300))), maximum: 64 * 1024 * 1024)
        let response = try await NativeDeadline.run(until: request.deadline) { try await self.post(request) }
        try flag.check(deadline)
        let parsed = try parse(response, key: key, url: url, maximum: request.maximum)
        let first = parsed["data"]?.arrayValue?.first
        if let encoded = first?["b64_json"]?.string, let bytes = Data(base64Encoded: encoded) { return bytes }
        guard let value = first?["url"]?.string else { throw invalid("服务未返回图像内容") }
        return try await NativeDeadline.run(until: deadline) { try await self.download(value, deadline, { flag.isCancelled }) }
    }

    /// Report a matched active flag; absent IDs still retain bounded one-use pre-cancellation.
    private func cancel(_ job: String) -> Bool {
        if let flag = active[job] { flag.cancel(); return true }
        if tombstones.contains(job) { return false }
        if tombstones.count >= 64 { tombstones.removeFirst() }
        tombstones.append(job)
        return false
    }

    /// Endpoint concatenation remains the existing base URL plus path suffix and is checked before any POST.
    private func endpoint(_ base: String, suffix: String) throws -> URL {
        var value = base
        while value.hasSuffix("/") { value.removeLast() }
        guard let url = URL(string: value + "/" + suffix) else { throw NativeNetworkPolicy.refused("服务地址必须是有效的 HTTP 或 HTTPS URL") }
        try NativeNetworkPolicy.provider(url)
        return url
    }

    /// Provider bytes remain bounded and only valid JSON enters response shape validation.
    private func parse(_ response: NativeHTTPReply, key: String, url: URL, maximum: Int) throws -> HostJSON {
        guard response.body.count <= maximum else { throw invalid("服务响应超过大小上限") }
        guard (200...299).contains(response.status) else {
            throw HostFailure(code: "PW_MODEL_STATUS", message: "服务返回 \(response.status)：" + NativeModelDiagnostic.excerpt(response.body, key: key, url: url))
        }
        do { return try JSONDecoder().decode(HostJSON.self, from: response.body) }
        catch { throw invalid("响应不是有效 JSON") }
    }

    /// Model whitespace is validated without rewriting the provider's existing model identifier.
    private func selectedModel(_ args: [String: HostJSON]) throws -> String {
        let model = try string(args, "model")
        guard !model.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { throw invalid("未选择模型") }
        return model
    }

    /// IPC string arguments retain type distinctions and never echo caller-controlled data into errors.
    private func string(_ args: [String: HostJSON], _ key: String) throws -> String {
        guard let value = args[key]?.string else { throw invalid("模型请求字符串参数缺失或类型错误") }
        return value
    }

    /// Existing generated-image formats are determined by bytes, never by a provider's claimed MIME.
    private static func imageMIME(_ data: Data) -> String? {
        let b = [UInt8](data.prefix(12))
        if b.count >= 4, Array(b.prefix(4)) == [0x89, 0x50, 0x4e, 0x47] { return "image/png" }
        if b.count >= 3, Array(b.prefix(3)) == [0xff, 0xd8, 0xff] { return "image/jpeg" }
        if b.count >= 12, String(bytes: b[0..<4], encoding: .ascii) == "RIFF", String(bytes: b[8..<12], encoding: .ascii) == "WEBP" { return "image/webp" }
        if b.count >= 6, ["GIF87a", "GIF89a"].contains(String(bytes: b.prefix(6), encoding: .ascii) ?? "") { return "image/gif" }
        return nil
    }

    /// Stable domain failures remain visible without attaching key material or entire request URLs.
    private func invalid(_ message: String) -> HostFailure { HostFailure(code: "PW_MODEL_ERROR", message: message) }
}

/// The storage actor reads this flag after queueing and immediately before atomic rename.
private final class NativeModelCancellation: Sendable {
    /// A mutex permits cancellation from Task handlers without actor hops or data races.
    private let value = Mutex(false)
    /// Flag reads are safe inside background filesystem transactions.
    var isCancelled: Bool { value.withLock { $0 } }
    /// Repeated cancellation is idempotent and never re-enables a stale job.
    func cancel() { value.withLock { $0 = true } }
    /// Every external stage checks both lifecycle cancellation and the shared absolute budget.
    func check(_ deadline: ContinuousClock.Instant) throws {
        try Task.checkCancellation()
        guard !isCancelled else { throw HostFailure(code: "PW_CANCELLED", message: "已取消") }
        guard deadline > .now else { throw NativeDeadline.expired() }
    }
}
